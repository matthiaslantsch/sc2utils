<?php
/**
 * Turn sc2reader's data files (tools/sc2reader/sc2reader/data/) into the game data files in src/gamedata/data/.
 *
 * Usage (from the repo root):
 *     php tools/generate/gamedata.php [output dir]
 *
 *     attributes.php   attributes.json: attribute id => [name, [value => display value]]. Ids whose entry is null
 *                      in the JSON are left out (sc2reader can't use them either).
 */
const SC2READER = __DIR__.'/../sc2reader';
const DEFAULT_OUTPUT = __DIR__.'/../../src/gamedata/data';

function fail(string $message): never {
	fwrite(\STDERR, "gamedata.php: {$message}\n");

	exit(1);
}

function export(mixed $value): string {
	if (is_int($value)) {
		return (string)$value;
	}
	if (is_string($value)) {
		return var_export($value, true);
	}
	if (is_array($value)) {
		$list = array_is_list($value);
		$items = array();
		foreach ($value as $key => $item) {
			$items[] = ($list ? '' : export($key).' => ').export($item);
		}

		return 'array('.implode(', ', $items).')';
	}
	fail('cannot export '.get_debug_type($value));
}

function readJson(string $path): array {
	$content = file_get_contents($path);
	if ($content === false) {
		fail("cannot read {$path}");
	}
	$data = json_decode($content, true, 512, \JSON_THROW_ON_ERROR);
	if (!is_array($data)) {
		fail("{$path}: expected a JSON object");
	}

	return $data;
}

function fileHeader(string $source): string {
	$commit = trim((string)shell_exec('git -C '.escapeshellarg(SC2READER).' rev-parse HEAD'));
	if (preg_match('/^[0-9a-f]{40}$/', $commit) !== 1) {
		fail('cannot read the sc2reader submodule commit');
	}
	$licence = file(SC2READER.'/LICENSE.txt', \FILE_IGNORE_NEW_LINES);
	if ($licence === false) {
		fail('cannot read the sc2reader licence');
	}
	$lines = array(
		'Generated by tools/generate/gamedata.php, do not edit.',
		"Source: sc2reader {$source} (submodule commit ".substr($commit, 0, 12).')',
		'',
		...$licence,
	);

	return "<?php\n/**\n".implode("\n", array_map(static fn (string $l): string => rtrim(" * {$l}"), $lines))."\n */\n";
}

/**
 * @return array<int, array{string, array<string, string>}>
 */
function attributes(): array {
	$data = readJson(SC2READER.'/sc2reader/data/attributes.json');
	if (!is_array($data['attributes'] ?? null)) {
		fail('attributes.json has no "attributes" object');
	}

	$ret = array();
	foreach ($data['attributes'] as $id => $entry) {
		if ($entry === null) {
			continue;
		}
		if (!is_numeric($id) || !is_array($entry) || count($entry) !== 2 || !is_string($entry[0]) || !is_array($entry[1])) {
			fail("attributes.json: malformed entry {$id}");
		}
		$values = array();
		foreach ($entry[1] as $key => $value) {
			// JSON object keys like "0" come back as ints from json_decode()
			$values[(string)$key] = (string)$value;
		}
		$ret[(int)$id] = array($entry[0], $values);
	}
	ksort($ret);

	return $ret;
}

function write(string $path, string $content): void {
	if (file_put_contents($path, $content) === false) {
		fail("cannot write {$path}");
	}
}

$output = $argv[1] ?? DEFAULT_OUTPUT;
if (!is_dir(SC2READER.'/sc2reader/data')) {
	fail('the sc2reader submodule is missing, run: git submodule update --init');
}
if (!is_dir($output) && !mkdir($output, 0o777, true)) {
	fail("cannot create {$output}");
}

$lines = array();
foreach (attributes() as $id => $entry) {
	$lines[] = "\t{$id} => ".export($entry).',';
}
write("{$output}/attributes.php", fileHeader('sc2reader/data/attributes.json')."\nreturn array(\n".implode("\n", $lines)."\n);\n");
